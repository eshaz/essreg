"""Generate the Linux driver's register header from src/esscat.tbl.

usage:
  python3 tools/linuxregs.py            write linux/es1869/regs.h
  python3 tools/linuxregs.py --check    fail if it is stale

The header gives each register's number, each field's register, shift and
mask, and the register list as an X-macro for the register hwdep and the
proc dump. It is GPL-2.0-or-later like the rest of the driver: the catalog's
author relicensed what the header takes from it for the driver.
"""

import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TBL = os.path.join(ROOT, "src", "esscat.tbl")
OUT = os.path.join(ROOT, "linux", "es1869", "regs.h")
sys.path.insert(0, os.path.join(ROOT, "tools"))
from regdoc import split_args, unquote  # noqa: E402

BANKS = ["BK_MIXER", "BK_CTRL", "BK_APORT", "BK_CPORT", "BK_PNPCARD",
         "BK_PNPLDN"]
RFLAGS = {"RF_READ_SIDEFX": 0x01, "RF_WRITEONLY": 0x02,
          "RF_NEEDS_IDLE": 0x04, "RF_ALIAS": 0x08, "RF_FM_PORT": 0x10}
LDNS = {"LDN_MPU": 0x10, "LDN_CDROM": 0x11, "LDN_MODEM": 0x12,
        "LDN_GP": 0x13}

HEADER = """\
/* SPDX-License-Identifier: GPL-2.0-or-later */
/*
 * The ES1869's registers and fields, generated by tools/linuxregs.py from
 * essreg's register catalog, src/esscat.tbl. Don't edit it: change the
 * catalog and run python3 tools/linuxregs.py.
 *
 * ES_R_* are register numbers, ES_F_*_REG/_SHIFT/_MASK a field's register
 * and bits, and ES1869_REGS(X) lists every register as
 * X(id, bank, ldn, addr, flags, name).
 *
 * (c) 2026 Ethan Halsall <ethan.s.halsall@gmail.com>
 */

#ifndef ES1869_REGS_H
#define ES1869_REGS_H

"""


def parse(path=TBL):
    """(regs, fields) of the catalog, in its order"""
    regs, fields = [], []
    with open(path, encoding="ascii") as f:
        for line in f:
            line = line.strip()
            m = re.match(r"(REG|FLD)\((.*)\)$", line)
            if not m:
                continue
            args = split_args(m.group(2))
            if m.group(1) == "REG":
                rid, bank, ldn, addr, rflags, name, _page = args
                flags = 0
                for fl in rflags.split("|"):
                    fl = fl.strip()
                    if fl and fl != "0":
                        flags |= RFLAGS[fl]
                regs.append({"id": rid[2:], "bank": bank,
                             "ldn": LDNS[ldn] if ldn in LDNS
                             else int(ldn, 0),
                             "addr": int(addr, 0), "flags": flags,
                             "name": unquote(name)})
            else:
                fid, rid, shift, width = args[:4]
                fields.append({"id": fid[2:], "reg": rid[2:],
                               "shift": int(shift), "width": int(width),
                               "label": unquote(args[11])})
    return regs, fields


def c_string(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def render():
    regs, fields = parse()
    out = [HEADER]
    out.append("// how a register is reached\n")
    for i, b in enumerate(BANKS):
        out.append("#define ES_%s %d\n" % (b, i))
    out.append("\n// register flags\n")
    for name, bit in RFLAGS.items():
        out.append("#define ES_%s 0x%02X\n" % (name, bit))
    out.append("\n// the optional logical devices, numbered after card "
               "register 25h\n")
    for name, n in LDNS.items():
        out.append("#define ES_%s 0x%02X\n" % (name, n))
    out.append("\n// registers\n")
    by_id = {}
    for r in regs:
        by_id[r["id"]] = r
        out.append("#define ES_R_%s 0x%02X // %s\n" % (r["id"], r["addr"],
                                                       r["name"]))
    out.append("\n// fields: register, shift and mask\n")
    for f in fields:
        mask = ((1 << f["width"]) - 1) << f["shift"]
        out.append("#define ES_F_%s_REG ES_R_%s // %s\n" %
                   (f["id"], f["reg"], f["label"]))
        out.append("#define ES_F_%s_SHIFT %d\n" % (f["id"], f["shift"]))
        out.append("#define ES_F_%s_MASK 0x%02X\n" % (f["id"], mask))
    out.append("\n// every register: X(id, bank, ldn, addr, flags, name)\n")
    out.append("#define ES1869_REGS(X) \\\n")
    lines = []
    for r in regs:
        flags = " | ".join("ES_" + n for n, b in RFLAGS.items()
                           if r["flags"] & b) or "0"
        lines.append("\tX(%s, ES_%s, 0x%02X, 0x%02X, %s, %s)" %
                     (r["id"], r["bank"], r["ldn"], r["addr"], flags,
                      c_string(r["name"])))
    out.append(" \\\n".join(lines) + "\n")
    out.append("\n#endif /* ES1869_REGS_H */\n")
    return "".join(out)


def main():
    text = render()
    if "--check" in sys.argv[1:]:
        try:
            with open(OUT, encoding="ascii", newline="") as f:
                old = f.read()
        except FileNotFoundError:
            old = None
        if old != text:
            print("%s is stale: run python3 tools/linuxregs.py" % OUT)
            return 1
        return 0
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="ascii", newline="\n") as f:
        f.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
