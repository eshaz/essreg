"""Fit the correction of Audio 2's DAC that snd-es1869's rate filter folds in.

usage:
  python3 tools/es1869treble.py            write linux/es1869/treble.h
  python3 tools/es1869treble.py --check    fail if it is stale
  python3 tools/es1869treble.py --last X   the fit for a DAC that keeps X
                                           of the last sample, printed only
  python3 tools/es1869treble.py --last X --amixer
                                           and as the amixer command that
                                           loads it into a running driver

The model is docs/AUDIO_PIPELINE.md's: with its stages off, the Audio 2 DAC
holds each sample for a period of its rate and keeps LAST of the one
before, (1 + LAST z^-1) / (1 + LAST). a2_treble takes that back with a
symmetric filter of SIDES taps each side of the centre, a stream frame
apart, which resample.c folds into the rate filter, one for the DAC at 1x,
2x and 3x of the stream's rate. Each is the minimax fit of the DAC's
inverse from 0 Hz to half the stream's rate, with a gain of 1 at 0 Hz.

The fit can't be exact at half the rate: there a symmetric filter's
response is flat, and the hold's still falls, so the error shrinks only as
about 1 / SIDES. The taps cost nothing a frame, since they fold into the
filter's own.

To follow a new measurement of the DAC, change LAST and run the tool. A
running driver takes a fit without a rebuild through its control "Audio 2
Treble Correction Taps", 16 side taps at 1x, 2x and 3x in turn, which the
next stream takes at its prepare; alsactl store keeps them over a boot.
"""

import argparse
import os
import sys

import numpy as np

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "linux", "es1869", "treble.h")

LAST = 0.062  # the DAC's share of the last sample, AUDIO_PIPELINE.md's fit
SIDES = 16  # the taps each side of the centre
OVERS = (1, 2, 3)  # the DAC's rates, over the stream's
POINTS = 8192  # the grid from 0 Hz to half the stream's rate
Q30 = 1 << 30

HEADER = """\
/* SPDX-License-Identifier: GPL-2.0-or-later */
/*
 * The correction of Audio 2's DAC that a2_treble folds into the rate filter,
 * generated by tools/es1869treble.py from the DAC's model. Don't edit it:
 * change the model there and run python3 tools/es1869treble.py.
 *
 * With its stages off, the DAC holds each sample for a period of its rate
 * and keeps ES_TREBLE_LAST_PPM of the one before. For the DAC at 1x, 2x and
 * 3x of the stream's rate, the taps each side of the centre, a stream frame
 * apart, in Q30, with a centre that makes their sum 1: the minimax fit of
 * the DAC's inverse from 0 Hz to half the stream's rate.
 *
 * (c) 2026 Ethan Halsall <ethan.s.halsall@gmail.com>
 */

#ifndef ES1869_TREBLE_H
#define ES1869_TREBLE_H

"""


def dac(w, over, last=LAST):
    """the DAC's gain at w, radians a stream frame, at over times the rate"""
    x = w / over
    hold = np.sinc(x / (2 * np.pi))
    return hold * np.abs(1 + last * np.exp(-1j * x)) / (1 + last)


def response(side, w):
    """the correction's gain at w: the centre and the side taps"""
    side = np.asarray(side, dtype=float)
    k = np.arange(1, len(side) + 1)
    return 1 + (2 * np.cos(np.outer(w, k)) - 2) @ side


def fit(over, last=LAST, sides=None):
    """the side taps by Remez's exchange, and the worst error of the gain
    with the DAC, relative. The basis 2 cos kw - 2 keeps the gain 1 at 0 Hz,
    where the error is none, so the grid starts past it"""
    sides = sides or SIDES
    w = np.linspace(0, np.pi, POINTS + 1)[1:]
    h = dac(w, over, last)
    f = 1 / h - 1
    basis = 2 * np.cos(np.outer(w, np.arange(1, sides + 1))) - 2
    ref = np.round((1 - np.cos(np.linspace(0, np.pi, sides + 1))) / 2 *
                   (POINTS - 1)).astype(int)
    sign = (-1.0) ** np.arange(sides + 1)
    for _ in range(100):
        a = np.hstack([basis[ref], (sign / h[ref])[:, None]])
        side = np.linalg.solve(a, f[ref])[:sides]
        e = h * (basis @ side - f)
        # the extremes, one for each run of a sign, the largest of it
        d = np.sign(np.diff(e))
        turn = np.nonzero(d[1:] != d[:-1])[0] + 1
        keep = []
        for i in np.concatenate([[0], turn, [len(e) - 1]]):
            if keep and np.sign(e[i]) == np.sign(e[keep[-1]]):
                if abs(e[i]) > abs(e[keep[-1]]):
                    keep[-1] = i
            else:
                keep.append(i)
        while len(keep) > sides + 1:
            keep.pop(0 if abs(e[keep[0]]) < abs(e[keep[-1]]) else -1)
        if len(keep) < sides + 1 or np.array_equal(keep, ref):
            break
        ref = np.array(keep)
    return side, float(np.abs(e).max())


def taps(last=LAST):
    """each rate's side taps in Q30, the worst error in dB and the peak gain
    of the correction in dB, with where it lies, in radians"""
    out = []
    w = np.linspace(0, np.pi, POINTS + 1)
    for over in OVERS:
        side, _ = fit(over, last)
        q = [int(round(v * Q30)) for v in side]
        db = 20 * np.log10(response(np.array(q) / Q30, w) * dac(w, over, last))
        gain = 20 * np.log10(response(np.array(q) / Q30, w))
        out.append((q, float(np.abs(db).max()), float(gain.max()),
                    float(w[np.argmax(gain)])))
    return out


def header(last=LAST):
    lines = [HEADER]
    lines.append("#define ES_TREBLE_LAST_PPM %d // the DAC's share of the "
                 "last sample\n" % round(last * 1e6))
    lines.append("#define ES_TREBLE_SIDES %d // the taps each side of the "
                 "centre\n\n" % SIDES)
    lines.append("// the side taps for the DAC at 1x, 2x and 3x of the "
                 "stream's rate\n")
    lines.append("static const s32 es1869_treble[%d][ES_TREBLE_SIDES] = {\n"
                 % len(OVERS))
    for over, (q, err, gain, at) in zip(OVERS, taps(last)):
        lines.append("\t// %dx: within %.3f dB, the gain %.2f dB at most\n"
                     % (over, err, gain))
        row = ", ".join(str(v) for v in q)
        text = "\t{ "
        for v in row.split(", "):
            piece = v + ", "
            if len(text.expandtabs(8)) + len(piece.rstrip()) > 79:
                lines.append(text.rstrip() + "\n")
                text = "\t  "
            text += piece
        lines.append(text.rstrip(", ") + " },\n")
    lines.append("};\n\n#endif /* ES1869_TREBLE_H */\n")
    return "".join(lines)


def main():
    p = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    p.add_argument("--check", action="store_true",
                   help="fail if linux/es1869/treble.h is stale")
    p.add_argument("--last", type=float,
                   help="print the fit for a DAC that keeps this much of "
                        "the last sample")
    p.add_argument("--amixer", action="store_true",
                   help="with --last, the amixer command that loads it")
    a = p.parse_args()
    if a.last is not None and a.amixer:
        fit = [v for q, _, _, _ in taps(a.last) for v in q]
        print("amixer -c ES1869 cset name='Audio 2 Treble Correction Taps' "
              + ",".join(str(v) for v in fit))
        return 0
    if a.last is not None:
        w = np.linspace(0, np.pi, 9)
        for over, (q, err, gain, at) in zip(OVERS, taps(a.last)):
            print("%dx: within %.3f dB, the gain %.2f dB at most, at %.3f of "
                  "the rate" % (over, err, gain, at / (2 * np.pi)))
            print("  taps " + ", ".join(str(v) for v in q))
            print("  dB   " + " ".join(
                "%.3f" % v for v in 20 * np.log10(dac(w, over, a.last))))
        return 0
    text = header()
    if a.check:
        with open(OUT, encoding="utf-8") as f:
            if f.read() != text:
                print("%s is stale: run python3 tools/es1869treble.py" % OUT)
                return 1
        return 0
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print("%s: %d taps each side, 1x to %dx" % (OUT, SIDES, OVERS[-1]))
    return 0


if __name__ == "__main__":
    sys.exit(main())
